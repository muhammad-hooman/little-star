export const getProductSlug = (product) => {
  const name = product.name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '')
  return `${name}-${product.id}`
}

export const getProductHref = (product) => `#/product/${getProductSlug(product)}`

